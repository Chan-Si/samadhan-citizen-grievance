export const getLocalizedCategories = (lang: Language): CategoryInfo[] => {
  let district = '';
  let state = '';
  try {
    const savedUser = localStorage.getItem('samadhan_user');
    if (savedUser) {
      const parsed = JSON.parse(savedUser);
      if (parsed && parsed.district) {
        district = parsed.district;
        for (const [st, districts] of Object.entries(STATES_AND_DISTRICTS)) {
          if (districts.includes(district)) {
            state = st;
            break;
          }
        }
      }
    }
  } catch (e) {
    console.error(e);
  }

  if (!district) district = 'Bangalore Urban';
  if (!state) state = 'Karnataka';

  const dict = CATEGORY_TRANSLATIONS[lang] || CATEGORY_TRANSLATIONS.en;
  
  return BASE_CATEGORIES.map(cat => {
    const title = dict[cat.title] || cat.title;
    const description = dict[cat.description] || cat.description;
    let routingDepartment = dict[cat.routingDepartment] || cat.routingDepartment;
    
    // Replace Guwahati/Kamrup Metropolitan/Assam with user's district and state dynamically!
    routingDepartment = routingDepartment
      .replace(/Kamrup Metropolitan/g, district)
      .replace(/Guwahati/g, district)
      .replace(/Dispur/g, district)
      .replace(/Assam/g, state);

    return {
      ...cat,
      title,
      description,
      routingDepartment,
      subtopics: cat.subtopics.map(sub => ({
        ...sub,
        title: dict[sub.title] || sub.title,
        description: dict[sub.description] || sub.description
      }))
    };
  });
};



